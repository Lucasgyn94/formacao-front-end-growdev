// Operador Lógico - Conjunção (and ou &&) = e
console.log("Operador Lógico - Conjunção");
console.log(5 > 3 && 7 === 7); // true
console.log(5 > 6 && 7 === 7); // false

// Operador Lógico - Disjunção (or ou ||) = ou
console.log("===========================\n");
console.log("Operador Lógico - Disjunção");
console.log(5 > 6 || 7 === 7); // true
console.log(3 > 5 || 4 < 8); // true

// Operador Lógico - Negação (not ou !) = não
console.log("===========================\n");
console.log("Operador Lógico - Negação");
console.log(!(5 > 6));
console.log(!(7 === 7));
