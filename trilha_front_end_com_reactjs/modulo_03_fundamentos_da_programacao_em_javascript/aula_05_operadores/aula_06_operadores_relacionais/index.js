// Operador Relacional - Maior
const num1 = 5;
const num2 = 7;

console.log(num2 > num1); // true

// Operador Relacional - Menor
console.log(num2 < num1); // false

// Operador Relacional - Maior Igual
console.log(num1 >= 5); // true

// Operador Relacional - Menor Igual
console.log(num2 <= 8); // true

// Operador Relacional - Extritamente igual
console.log(num1 === '5'); // false

// Operador Relacional - Extritamente Diferente
console.log(num1 !== 5); // false
